/// Hijri (Umm al-Qura) display dates for the calendar.
///
/// Why it exists: the calendar can show the Hijri day under each Gregorian day and the
/// Hijri month(s) under the month title (design spec 2.3). Display only: every date she
/// records stays Gregorian ISO, and nothing here is ever stored.
///
/// Twin of `hijriDay` / `hijriMonthLine` in `apps/web/src/lib/calendar/grid.ts`, which
/// ask the browser's Intl for the same calendar. The two are bound by
/// `fixtures/domain/hijri.json` (generated from Node's ICU), so both clients print the
/// same day.
///
/// Why a generated table and not a pub package: `hijri` 3.0.1 (and `jhijri`,
/// `hijri_calendar`, which share its table) differed from ICU on 22 of 252 sampled days,
/// one day off in Dec 2024 and in 2029-2030, so the app and the website would have shown
/// different days. `hijri_months.g.dart` holds the first day of every Umm al-Qura month
/// from 1356 to 1500 AH (1937 to 2077) as ICU reports it; the lookup is a binary search.
/// Offline, no dependency, regenerated by `scripts/domain/gen-hijri-fixture.mjs`.
library;

import 'dates.dart';
import 'hijri_months.g.dart';

/// One Hijri date, as numbers: day 1-30, month 1-12, year in AH.
class HijriDate {
  const HijriDate(this.day, this.month, this.year);
  final int day;
  final int month;
  final int year;
}

/// The Hijri date of [iso] (`YYYY-MM-DD`), or null when [iso] is not a real date or
/// falls outside the years the Umm al-Qura table covers. Never throws: a missing
/// secondary label is the only failure mode, same as the website.
HijriDate? hijriDate(String iso) {
  if (!isValidISODate(iso)) return null;
  final epochDay = fromISO(iso).millisecondsSinceEpoch ~/ Duration.millisecondsPerDay;
  final last = hijriMonthStarts.length - 1; // the closing sentinel is not a month
  if (epochDay < hijriMonthStarts.first || epochDay >= hijriMonthStarts[last]) return null;
  // Largest index whose month starts on or before this day.
  var lo = 0;
  var hi = last - 1;
  while (lo < hi) {
    final mid = (lo + hi + 1) >> 1;
    if (hijriMonthStarts[mid] <= epochDay) {
      lo = mid;
    } else {
      hi = mid - 1;
    }
  }
  return HijriDate(epochDay - hijriMonthStarts[lo] + 1, lo % 12 + 1, hijriFirstYear + lo ~/ 12);
}

/// The Hijri day of the month for [iso], Western digits ("13"), or '' when unavailable.
String hijriDay(String iso) => hijriDate(iso)?.day.toString() ?? '';

/// Hijri month names by language, CLDR spellings (Node ICU 77.1, Umm al-Qura), index 0 =
/// Muharram. These are locale data like a date-format pattern, not copy, so they live
/// beside the conversion rather than in the ARB files.
const hijriMonthNames = <String, List<String>>{
  'ar': ['محرم', 'صفر', 'ربيع الأول', 'ربيع الآخر', 'جمادى الأولى', 'جمادى الآخرة', 'رجب', 'شعبان', 'رمضان', 'شوال', 'ذو القعدة', 'ذو الحجة'],
  'en': ['Muharram', 'Safar', 'Rabiʻ I', 'Rabiʻ II', 'Jumada I', 'Jumada II', 'Rajab', 'Shaʻban', 'Ramadan', 'Shawwal', 'Dhuʻl-Qiʻdah', 'Dhuʻl-Hijjah'],
  'fr': ['Mouharram', 'Safar', 'Rabia al awal', 'Rabia ath-thani', 'Joumada al oula', 'Joumada ath-thania', 'Rajab', 'Chaabane', 'Ramadan', 'Chawwal', 'Dhou al qi`da', 'Dhou al-hijja'],
  'es': ['Muharram', 'Safar', 'Rabiʻ I', 'Rabiʻ II', 'Jumada I', 'Jumada II', 'Rajab', 'Shaʻban', 'Ramadán', 'Shawwal', 'Dhuʻl-Qiʻdah', 'Dhuʻl-Hijjah'],
};

/// The era after the year: "هـ" in Arabic, "AH" elsewhere (what Intl prints).
const _eraByLanguage = {'ar': 'هـ'};
const _defaultEra = 'AH';

/// The Hijri month(s) and year that the Gregorian span [firstIso]..[lastIso] covers, as
/// one line: "جمادى الأولى – جمادى الآخرة 1448 هـ". One month gives "رجب 1448 هـ". The
/// year is the year of [lastIso], as on the website. [locale] is a language code or tag
/// ("ar", "en-US"); an unknown language falls back to English names. '' when either end
/// is unavailable.
///
/// A dash between month names carries no digits, so no bidi marks are needed; the year
/// is written after both names (digits stay Western, ADR-069).
String hijriMonthLine(String firstIso, String lastIso, String locale) {
  final a = hijriDate(firstIso);
  final b = hijriDate(lastIso);
  if (a == null || b == null) return '';
  final language = locale.split(RegExp('[-_]')).first.toLowerCase();
  final names = hijriMonthNames[language] ?? hijriMonthNames['en']!;
  final era = _eraByLanguage[language] ?? _defaultEra;
  final from = names[a.month - 1];
  final to = names[b.month - 1];
  final months = from == to ? from : '$from – $to';
  return '$months ${b.year} $era';
}

/// A full Hijri date for assistive technology: "9 جمادى الأولى 1448 هـ". Empty when the
/// date is unavailable.
String hijriFullDate(String iso, String locale) {
  final h = hijriDate(iso);
  if (h == null) return '';
  final language = locale.split(RegExp('[-_]')).first.toLowerCase();
  final names = hijriMonthNames[language] ?? hijriMonthNames['en']!;
  return '${h.day} ${names[h.month - 1]} ${h.year} ${_eraByLanguage[language] ?? _defaultEra}';
}
