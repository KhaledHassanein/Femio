#!/usr/bin/env node
/**
 * Generates, from Node's ICU (Umm al-Qura calendar):
 *   1. fixtures/domain/hijri.json, the common answer both clients must reproduce;
 *   2. apps/mobile/lib/domain/hijri_months.g.dart, the app's month-start table.
 *
 * Why it exists: the website gets Hijri dates from the browser's Intl; Dart has no Intl
 * calendar for it. The pub packages tried (hijri 3.0.1, jhijri, hijri_calendar all
 * share one table) disagreed with ICU on 22 of 252 sampled days, so the app carries
 * the month starts ICU itself reports and the fixture proves the two agree. Both files
 * are committed; a change to either is a change a reviewer must look at. The fixture
 * samples days independently of the table lookup, so it is not true by construction.
 *
 * Cases: the 1st, 10th and 20th of every month from 2024-01 to 2030-12 (day, month
 * index, year) plus the Arabic month line for every Gregorian month of 2026-2027
 * (the same strings the website prints under the month title).
 *
 * Run from the repository root: node scripts/domain/gen-hijri-fixture.mjs
 */
import { writeFileSync } from "node:fs";

const DAY_MS = 86_400_000;

const BASE = "-u-ca-islamic-umalqura-nu-latn";
const part = (opts) => new Intl.DateTimeFormat("en" + BASE, { ...opts, timeZone: "UTC" });
const NUM = { day: part({ day: "numeric" }), month: part({ month: "numeric" }), year: part({ year: "numeric" }) };
const at = (iso) => new Date(`${iso}T00:00:00Z`);
const two = (n) => String(n).padStart(2, "0");

const cases = [];
for (let year = 2024; year <= 2030; year += 1) {
  for (let month = 1; month <= 12; month += 1) {
    for (const day of [1, 10, 20]) {
      const iso = `${year}-${two(month)}-${two(day)}`;
      // formatToParts "numeric" on the Hijri calendar yields the era-less number; read it back as an integer.
      const d = at(iso);
      cases.push({
        input: { iso },
        expected: {
          day: String(Number(NUM.day.format(d))),
          month: Number(NUM.month.format(d)),
          year: Number(NUM.year.format(d).replace(/\D/g, "")),
        },
      });
    }
  }
}

// The Arabic month line, exactly as apps/web/src/lib/calendar/grid.ts builds it.
const AR = "ar-SA" + BASE;
const arMonth = new Intl.DateTimeFormat(AR, { month: "long", timeZone: "UTC" });
const arYear = new Intl.DateTimeFormat(AR, { year: "numeric", timeZone: "UTC" });
for (const year of [2026, 2027]) {
  for (let month = 1; month <= 12; month += 1) {
    const first = `${year}-${two(month)}-01`;
    const last = `${year}-${two(month)}-${two(new Date(Date.UTC(year, month, 0)).getUTCDate())}`;
    const a = arMonth.format(at(first));
    const b = arMonth.format(at(last));
    const y = arYear.format(at(last));
    cases.push({ input: { first, last, locale: "ar" }, expected: { line: a === b ? `${a} ${y}` : `${a} – ${b} ${y}` } });
  }
}

const doc = {
  $comment:
    "Hijri (Umm al-Qura) answers from Node ICU " + process.versions.icu + ". Day cases: ISO date to Hijri day (string, Western digits), month index 1-12, year. Line cases: the Arabic month line under a Gregorian month. Generated by scripts/domain/gen-hijri-fixture.mjs; reviewed by hand.",
  cases,
};
writeFileSync("fixtures/domain/hijri.json", JSON.stringify(doc, null, 2) + "\n");
console.log(`wrote ${cases.length} cases`);

// The app's month-start table: epoch day (days since 1970-01-01 UTC) of the first day
// of every Hijri month from 1 Muharram 1356 to 1 Muharram 1501 (14 Mar 1937 to 2077),
// the span the older Dart tables also cover. The last entry closes the final month.
const FIRST_YEAR = 1356;
const LAST_YEAR = 1501;
const parts = new Intl.DateTimeFormat("en" + BASE, { day: "numeric", month: "numeric", year: "numeric", timeZone: "UTC" });
const starts = [];
for (let ms = Date.UTC(1937, 2, 1); starts.length < (LAST_YEAR - FIRST_YEAR) * 12 + 1; ms += DAY_MS) {
  const p = Object.fromEntries(parts.formatToParts(new Date(ms)).map((x) => [x.type, x.value]));
  const year = Number(p.year.replace(/\D/g, ""));
  if (year < FIRST_YEAR) continue;
  if (Number(p.day) === 1) starts.push(ms / DAY_MS);
}
const rows = [];
for (let i = 0; i < starts.length; i += 10) rows.push("  " + starts.slice(i, i + 10).join(", ") + ",");
const dart = `// GENERATED by scripts/domain/gen-hijri-fixture.mjs from Node ICU ${process.versions.icu}. Do not edit by hand.
//
// First day of every Umm al-Qura month, as days since 1970-01-01 UTC, from 1 Muharram
// ${FIRST_YEAR} AH (index 0) to 1 Muharram ${LAST_YEAR} AH (the last entry closes the final
// month). Index i is month (i % 12) + 1 of year ${FIRST_YEAR} + i ~/ 12. Read by domain/hijri.dart;
// bound to the website by fixtures/domain/hijri.json.
library;

const int hijriFirstYear = ${FIRST_YEAR};

const List<int> hijriMonthStarts = [
${rows.join("\n")}
];
`;
writeFileSync("apps/mobile/lib/domain/hijri_months.g.dart", dart);
console.log(`wrote ${starts.length} month starts`);
