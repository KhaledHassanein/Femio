#!/usr/bin/env node
/**
 * Generate the Android app's colours from the website's canonical tokens (P3.1).
 *
 * `assets/brand/tokens/femio.tokens.css` is the one source of truth for Femio's
 * colours. The Flutter app reads them through `apps/mobile/lib/theme/tokens.g.dart`,
 * which this script writes, so a colour changed for the website changes in the app
 * on the next run, and the two can never drift apart by hand.
 *
 * It reads the two `:root` blocks (primitives, then light semantics) and the
 * `[data-theme="dark"]` block, resolves every `var()` chain to a literal, and emits
 * every custom property that resolves to a colour.
 *
 *   node scripts/design/tokens-to-dart.mjs           write the file
 *   node scripts/design/tokens-to-dart.mjs --check   fail if the file is stale (gate)
 */
import { readFileSync, writeFileSync } from "node:fs";

const CSS = "assets/brand/tokens/femio.tokens.css";
const OUT = "apps/mobile/lib/theme/tokens.g.dart";

const css = readFileSync(CSS, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");

/** The declarations inside every top-level block whose selector matches exactly. */
function blocks(selector) {
  const out = new Map();
  let at = 0;
  for (;;) {
    const start = css.indexOf(`${selector} {`, at);
    if (start === -1) break;
    // Only top-level occurrences: the selector must start a line.
    if (start > 0 && css[start - 1] !== "\n") {
      at = start + 1;
      continue;
    }
    const end = css.indexOf("\n}", start);
    const body = css.slice(css.indexOf("{", start) + 1, end);
    for (const m of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) out.set(m[1], m[2].trim());
    at = end;
  }
  return out;
}

const root = blocks(":root");
const dark = new Map([...root, ...blocks('[data-theme="dark"]')]);

function resolve(vars, value, depth = 0) {
  if (depth > 20) throw new Error(`var() cycle at ${value}`);
  const m = value.match(/^var\(--([a-z0-9-]+)\)$/);
  if (!m) return value;
  const next = vars.get(m[1]);
  if (next === undefined) throw new Error(`unresolved var(--${m[1]})`);
  return resolve(vars, next, depth + 1);
}

/** `#RRGGBB`, `#RGB` or `rgb(r g b / a)` → Dart 0xAARRGGBB, else null. */
function toArgb(value) {
  let m = value.match(/^#([0-9a-f]{6})$/i);
  if (m) return `0xFF${m[1].toUpperCase()}`;
  m = value.match(/^#([0-9a-f]{3})$/i);
  if (m) return `0xFF${[...m[1]].map((c) => c + c).join("").toUpperCase()}`;
  m = value.match(/^rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)\s*(?:[/,]\s*([\d.]+%?))?\s*\)$/i);
  if (m) {
    let a = m[4] === undefined ? 1 : m[4].endsWith("%") ? parseFloat(m[4]) / 100 : parseFloat(m[4]);
    const hex = (n) => Number(n).toString(16).padStart(2, "0").toUpperCase();
    return `0x${hex(Math.round(a * 255))}${hex(m[1])}${hex(m[2])}${hex(m[3])}`;
  }
  return null;
}

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const dartName = (name) => (/^[0-9]/.test(name) ? `c${name}` : camel(name));

function palette(vars) {
  const out = new Map();
  for (const [name, raw] of vars) {
    let value;
    try {
      value = resolve(vars, raw);
    } catch {
      continue;
    }
    const argb = toArgb(value);
    if (argb) out.set(dartName(name), argb);
  }
  return out;
}

const light = palette(root);
const darkPalette = palette(dark);
const names = [...light.keys()].filter((n) => darkPalette.has(n)).sort();

const lines = [
  "// GENERATED by scripts/design/tokens-to-dart.mjs from",
  "// assets/brand/tokens/femio.tokens.css. Do not edit: change the CSS and re-run.",
  "// ignore_for_file: constant_identifier_names",
  "",
  "import 'package:flutter/painting.dart';",
  "",
  "/// Every Femio colour token, resolved, for one theme.",
  "class FemioPalette {",
  "  const FemioPalette._({",
  ...names.map((n) => `    required this.${n},`),
  "  });",
  "",
  ...names.map((n) => `  final Color ${n};`),
  "",
  "  static const light = FemioPalette._(",
  ...names.map((n) => `    ${n}: Color(${light.get(n)}),`),
  "  );",
  "",
  "  static const dark = FemioPalette._(",
  ...names.map((n) => `    ${n}: Color(${darkPalette.get(n)}),`),
  "  );",
  "}",
  "",
];
const output = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== output) {
    console.error(
      `✗ Dart tokens are stale: ${OUT} does not match ${CSS}.\n` +
        "  Run `node scripts/design/tokens-to-dart.mjs` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`✓ Dart tokens match the CSS (${names.length} colours, light and dark).`);
} else {
  writeFileSync(OUT, output);
  console.log(`wrote ${OUT}: ${names.length} colours, light and dark`);
}
