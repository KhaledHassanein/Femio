"""Generates the reviewed tip and visit-question catalogue for the app (ADR-079).

Why it exists: the tips and persona visit questions are reviewed sentences with a source each,
kept in one JSON file (docs/content/assistant/catalogue.json). The app needs them as Dart
constants (triggers, sources, English text for a model to order) and as ARB strings in four
languages. Writing both by hand would let them drift, so this script writes both from the one
file and fails on any unknown id, stage, term or language.

Run from the repo root:  python -X utf8 scripts/mobile/gen_tip_catalogue.py
"""
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
SOURCE = REPO / "docs/content/assistant/catalogue.json"
MOBILE = REPO / "apps/mobile"
DOMAIN_OUT = MOBILE / "lib/domain/assistant/tip_catalogue.g.dart"
TEXT_OUT = MOBILE / "lib/features/assistant/catalogue_text.g.dart"
L10N = MOBILE / "lib/l10n"
LANGS = ("en", "ar", "fr", "es")
STAGES = {"period", "ttc", "pregnant", "postpartum", "menopause"}
TRYING = {"justStarted", "under6", "sixTo12", "over12"}
PREFIX = {"tips": "tip_", "visitQuestions": "visitQ_"}
# Question ids the rule bank in visit_summary.dart already uses.
RULE_QUESTION_IDS = {"cycleSpread", "ttcTests", "ovulation", "folicAcid", "painfulPeriods", "heavyPeriods",
                     "moodCycle", "skinHair", "tiredness", "menopause", "pregnancyNext", "pregnancyMovements",
                     "anythingElse"}


def fail(msg):
    sys.exit(f"gen_tip_catalogue: {msg}")


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def vocabulary():
    text = (MOBILE / "lib/domain/log_vocabulary.g.dart").read_text(encoding="utf-8")
    return set(re.findall(r"LogTerm\('([A-Za-z]+)'", text))


def trigger_dart(t, terms):
    unknown = set(t) - {"stage", "term", "pregnancyWeeks", "postpartumWeeks", "tryingFor", "irregular", "ageFrom"}
    if unknown:
        fail(f"unknown trigger keys {unknown}")
    stages = t["stage"]
    if not stages or set(stages) - STAGES:
        fail(f"bad stages {stages}")
    parts = ["stages: {" + ", ".join(f"StageBand.{s}" for s in stages) + "}"]
    if "term" in t:
        term = t["term"]
        if term["key"] not in terms:
            fail(f"unknown term {term['key']}")
        parts.append(f"term: TermRule('{term['key']}', {int(term['minDays'])}, {int(term['windowDays'])})")
    for k in ("pregnancyWeeks", "postpartumWeeks"):
        if k in t:
            a, b = t[k]
            parts.append(f"{k}: ({int(a)}, {int(b)})")
    if "tryingFor" in t:
        if set(t["tryingFor"]) - TRYING:
            fail(f"bad tryingFor {t['tryingFor']}")
        parts.append("tryingFor: {" + ", ".join(f"TryingFor.{v}" for v in t["tryingFor"]) + "}")
    if "irregular" in t:
        parts.append(f"irregular: {'true' if t['irregular'] else 'false'}")
    if "ageFrom" in t:
        parts.append(f"ageFrom: {int(t['ageFrom'])}")
    return "PersonalTrigger(" + ", ".join(parts) + ")"


def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    terms = vocabulary()
    seen = set()
    for kind in PREFIX:
        for item in data[kind]:
            i = item["id"]
            if not re.fullmatch(r"[a-z][A-Za-z0-9]*", i) or i in seen:
                fail(f"bad or duplicate id {i}")
            if kind == "visitQuestions" and i in RULE_QUESTION_IDS:
                fail(f"{i} clashes with a rule question id")
            seen.add(i)
            for lang in LANGS:
                if not item.get(lang, "").strip():
                    fail(f"{i} has no {lang} text")
            src = item["source"]
            if not src["url"].startswith("https://") or not src["publisher"]:
                fail(f"{i} has a bad source")

    out = [
        "// GENERATED by scripts/mobile/gen_tip_catalogue.py from docs/content/assistant/catalogue.json.",
        "// Do not edit by hand: edit the JSON and run the script.",
        "//",
        "// The reviewed tips and persona visit questions (ADR-079): when each fits, and its source.",
        "// The words she reads are in the ARB files (tip_<id>, visitQ_<id>); the English here is only",
        "// for a model that puts ids in order.",
        "",
        "import '../../data/profile.dart' show TryingFor;",
        "import 'personal_triggers.dart';",
        "import 'pseudonymised_profile.dart' show StageBand;",
        "",
    ]
    names = {"tips": ("tipCatalogue", "tipEnglish"), "visitQuestions": ("visitQuestionCatalogue", "catalogueQuestionEnglish")}
    for kind, (list_name, en_name) in names.items():
        out.append(f"const {list_name} = <PersonalItem>[")
        for item in data[kind]:
            src = item["source"]
            out.append(f"  PersonalItem({dart_str(item['id'])}, {trigger_dart(item['trigger'], terms)}, "
                       f"publisher: {dart_str(src['publisher'])}, url: {dart_str(src['url'])}),")
        out.append("];")
        out.append("")
        out.append(f"const {en_name} = <String, String>{{")
        for item in data[kind]:
            out.append(f"  {dart_str(item['id'])}: {dart_str(item['en'])},")
        out.append("};")
        out.append("")
    DOMAIN_OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")

    txt = [
        "// GENERATED by scripts/mobile/gen_tip_catalogue.py. Do not edit by hand.",
        "//",
        "// Looks up a catalogue item's sentence in her language.",
        "",
        "import '../../l10n/app_localizations.dart';",
        "",
    ]
    for kind, fn in (("tips", "tipText"), ("visitQuestions", "catalogueQuestionText")):
        txt.append(f"/// The reviewed sentence for catalogue id [id], or null for an unknown id.")
        txt.append(f"String? {fn}(L10n l, String id) => switch (id) {{")
        for item in data[kind]:
            txt.append(f"  {dart_str(item['id'])} => l.{PREFIX[kind]}{item['id']},")
        txt.append("  _ => null,")
        txt.append("};")
        txt.append("")
    TEXT_OUT.write_text("\n".join(txt), encoding="utf-8", newline="\n")

    wanted = {f"{PREFIX[k]}{it['id']}": it for k in PREFIX for it in data[k]}
    for lang in LANGS:
        p = L10N / f"app_{lang}.arb"
        arb = json.loads(p.read_text(encoding="utf-8"))
        stale = [k for k in arb if (k.startswith("tip_") or k.startswith("visitQ_")) and k not in wanted
                 and k.removeprefix("visitQ_") not in RULE_QUESTION_IDS]
        for k in stale:
            arb.pop(k)
        for key, item in wanted.items():
            arb[key] = item[lang]
        p.write_text(json.dumps(arb, ensure_ascii=False, indent=2), encoding="utf-8", newline="\n")
    print(f"ok: {len(data['tips'])} tips, {len(data['visitQuestions'])} visit questions, 4 locales")


if __name__ == "__main__":
    main()
